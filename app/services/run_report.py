def _rule_title(rule: str, lang: str) -> str:
    titles = RULE_TITLES.get(rule)
    return titles[SUPPORTED_LANGUAGES.index(lang)] if titles else rule


def _recommendation(rule: str, lang: str) -> str:
    source = RECOMMENDATIONS_ES if lang == "es" else RECOMMENDATIONS
    return source.get(rule, TEXTS[lang]["default_fix"])


def render_run_report(run: dict[str, Any], lang: str = "en") -> str:
    """Return the full HTML report for one stored simulation run."""
    lang = lang if lang in SUPPORTED_LANGUAGES else "en"
    t = TEXTS[lang]
    e = lambda value: escape(str(value))  # noqa: E731

    if run.get("breached"):
        verdict, color = t["breached"], "#b42318"
    elif run.get("conclusive") is False:
        verdict, color = t["inconclusive"], "#667085"
    else:
        verdict, color = t["secured"], "#067647"

    rows = "".join(
        f"<tr><td class='sev' style='color:{SEVERITY_COLORS.get(str(item.get('severity')).lower(), '#475467')}'>"
        f"{e(str(item.get('severity', '')).upper())}</td>"
        f"<td>{e(owasp_label(item.get('rule', '')))}</td>"
        f"<td>{e(_rule_title(item.get('rule', ''), lang))}</td>"
        f"<td>{e(item.get('description', ''))}</td>"
        f"<td>{e(_recommendation(item.get('rule', ''), lang))}</td></tr>"
        for item in run.get("evidence", [])
    )
    findings = (
        f"<table><tr><th>{t['severity']}</th><th>{t['owasp']}</th><th>{t['finding']}</th>"
        f"<th>{t['detail']}</th><th>{t['fix']}</th></tr>{rows}</table>"
        if rows else f"<p>{t['no_findings']}</p>"
    )
    transcript = "".join(
        f"<div class='msg {e(m.get('role', ''))}'><div class='who'>"
        f"{t['attacker'] if m.get('role') == 'user' else t['assistant']}</div>"
        f"{e(m.get('content', ''))}</div>"
        for m in run.get("history", [])
    )
    inconclusive = (
        f"<p class='meta'>{e(run['inconclusive_reason'])}</p>"
        if run.get("conclusive") is False and run.get("inconclusive_reason") else ""
    )

    return f"""<!doctype html>
<html lang="{lang}"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{t['title']} · {e(run.get('run_id', ''))}</title><style>{_CSS}</style></head>
<body>
<h1>{t['title']}</h1>
<p class="meta">{t['run']}: {e(run.get('run_id', ''))} · {t['date']}: {e(run.get('completed_at') or run.get('created_at', ''))}<br>
{t['strategy']}: {e(run.get('strategy', ''))} · {t['target']}: {e(run.get('target_id') or t['builtin'])} ·
{t['turns']}: {e(run.get('total_turns', ''))}</p>
<h2>{t['verdict']}</h2>
<span class="verdict" style="background:{color}">{verdict}</span>{inconclusive}
<p>{t['defense']}: {e(run.get('defense_efficiency_score', '-'))}/10 ·
{t['aggression']}: {e(run.get('attacker_aggression_level', '-'))}/5</p>
<h2>{t['findings']}</h2>{findings}
<h2>{t['analysis']}</h2><p>{e(run.get('analysis', ''))}</p>
<h2>{t['transcript']}</h2>{transcript}
<footer>{t['footer']}</footer>
</body></html>"""
